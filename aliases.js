  // ---------------------------------------------------------- 匹配引擎
  function norm(s) { return String(s == null ? "" : s).toLowerCase(); }

  // 标点（中英）统一清除，避免"？/，"阻断子串匹配
  var PUNCT = /[，。？！、；：“”‘’（）《》【】…—·.,!?;:'"()\[\]<>{}\/\\|@#$%^&*+=~`]/g;

  function stripStopwords(s) {
    s = norm(s);
    for (var i = 0; i < STOP_MULTI.length; i++) {
      if (s.indexOf(STOP_MULTI[i]) > -1) s = s.split(STOP_MULTI[i]).join(" ");
    }
    if (STOP_CHAR) {
      var re = new RegExp("[" + STOP_CHAR + "]", "g");
      s = s.replace(re, " ");
    }
    s = s.replace(PUNCT, " ");
    return s.replace(/\s+/g, " ").trim();
  }

  // 低信号通用词：出现在太多卡片里，单独命中不足以定位。
  // ① 作为"直接子串"时不再给满分 100（否则"平均/概率"这类词会把所有含该词的卡片顶到最高）；
  // ② 作为"概念桥 canon"时只给基础分 60，精准规范词给 72+。
  var GENERIC = ["概率", "几率", "风险", "期望", "期望值", "收入", "房价", "等待时间", "比例", "价值", "时间", "相关", "平均"];

  function containsGeneric(q) {
    for (var i = 0; i < GENERIC.length; i++) {
      if (q.indexOf(GENERIC[i]) > -1) return true;
    }
    return false;
  }

  // 返回 {hit, score}：score 越高越相关。
  // 概念桥评分模型（避免"通用词埋没精准卡片"）：
  //   - 仅命中通用 canon       → 60（基础分）
  //   - 命中 ≥1 个精准 canon   → 72，且每多命中一个精准 canon +3（上限 +15）
  //       → 这样"平均陷阱"卡（独有 中位数/偏态/median）会比仅提及"均值"的卡片更高
  //   - 长口语说法（触发 say≥3 字）且命中精准 canon → 升到 82（强口语短语加成），再叠加精准数加成
  // 注意：说法触发用 qRawN（仅去标点、保留停用词），避免"多少/怎么/是不是"被提前剥掉，
  //       导致更长的口语说法（如"每个月工资到账要还多少"）整条失配。
  function _scanList(list, qRawN, hay, score, allowStrong) {
    for (var i = 0; i < list.length; i++) {
      var C = list[i];
      var trig = false, trigSayLen = 0;
      for (var j = 0; j < C.say.length; j++) {
        if (qRawN.indexOf(C.say[j]) > -1) {
          trig = true;
          if (C.say[j].length > trigSayLen) trigSayLen = C.say[j].length;
        }
      }
      if (!trig) continue;
      var specific = 0, any = false;
      for (var k = 0; k < C.canon.length; k++) {
        if (hay.indexOf(C.canon[k]) > -1) {
          any = true;
          if (GENERIC.indexOf(C.canon[k]) === -1) specific += 1;
        }
      }
      if (!any) continue;
      // 不可 break：取"全部 canon 命中的最高组合分"，否则首个命中的通用词会覆盖其后精准词。
      var tier = specific > 0 ? 72 : 60;
      if (allowStrong && trigSayLen >= 3 && specific > 0) tier = 82;   // 强口语短语 + 精准规范词
      var bonus = Math.min(specific, 5) * 3;                            // 命中越多精准规范词越相关
      var total = tier + bonus;
      if (score < total) score = total;
    }
    return score;
  }

  function matchHay(qRaw, hay) {
    hay = norm(hay);
    var q = stripStopwords(qRaw);                       // 去停用词+标点，用于"直接子串"
    var qRawN = norm(qRaw).replace(PUNCT, "");          // 仅去标点，保留停用词，用于"说法触发"
    var score = 0;
    // 直接子串满分 100：仅当查询本身不是通用词（避免"平均/概率"等把一堆卡片顶到最高），
    // 且长度≥2（短词歧义大，交给概念桥）。
    if (q.length >= 2 && !containsGeneric(q) && hay.indexOf(q) > -1) score = 100;
    score = _scanList(CONCEPTS, qRawN, hay, score, false);
    score = _scanList(PHRASES, qRawN, hay, score, true);
    return { hit: score > 0, score: score };
  }

  // 供 UI 展示"触发了哪些概念"（可选，用于结果下方标签）
  function triggeredConcepts(qRaw) {
    var qRawN = norm(qRaw).replace(PUNCT, "");
    var out = [];
    for (var i = 0; i < CONCEPTS.length; i++) {
      var C = CONCEPTS[i], trig = false;
      for (var j = 0; j < C.say.length; j++) { if (qRawN.indexOf(C.say[j]) > -1) { trig = true; break; } }
      if (trig) out.push(C.c);
    }
    return out;
  }

  window.LMAliases = {
    STOP_MULTI: STOP_MULTI,
    STOP_CHAR: STOP_CHAR,
    CONCEPTS: CONCEPTS,
    PHRASES: PHRASES,
    stripStopwords: stripStopwords,
    matchHay: matchHay,
    triggeredConcepts: triggeredConcepts
  };
